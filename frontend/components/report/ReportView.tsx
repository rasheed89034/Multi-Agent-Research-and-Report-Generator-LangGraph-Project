"use client";

import { useRef } from "react";
import CitationChip from "./CitationChip";
import type { Source } from "@/lib/types";

function withCitations(text: string, sources: Source[]) {
  return text.split(/(\[\d+\])/g).map((part, i) => {
    const m = part.match(/^\[(\d+)\]$/);
    return m ? <CitationChip key={i} n={+m[1]} source={sources[+m[1] - 1]} /> : <span key={i}>{part}</span>;
  });
}

async function downloadPDF(markdown: string, sources: Source[], title: string) {
  const { default: jsPDF } = await import("jspdf");

  const pdf = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });

  const PW = pdf.internal.pageSize.getWidth();   // 210
  const PH = pdf.internal.pageSize.getHeight();  // 297
  const ML = 18, MR = 18, MT = 20, MB = 20;
  const CW = PW - ML - MR;

  // Dark background fill helper
  const fillBackground = () => {
    pdf.setFillColor(15, 17, 23);
    pdf.rect(0, 0, PW, PH, "F");
  };
  fillBackground();

  // Accent line at top
  pdf.setDrawColor(99, 102, 241);
  pdf.setLineWidth(0.8);
  pdf.line(ML, MT - 6, PW - MR, MT - 6);

  let y = MT;

  const newPage = () => {
    pdf.addPage();
    fillBackground();
    pdf.setDrawColor(99, 102, 241);
    pdf.setLineWidth(0.8);
    pdf.line(ML, MT - 6, PW - MR, MT - 6);
    y = MT;
  };

  const guard = (need: number) => {
    if (y + need > PH - MB) newPage();
  };

  // Strip [n] citation markers for clean PDF text
  const clean = (s: string) => s.replace(/\[\d+\]/g, "").trim();

  for (const raw of markdown.split("\n")) {
    const line = raw.trimEnd();
    if (!line) { y += 3; continue; }

    if (line.startsWith("# ")) {
      guard(14);
      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(22);
      pdf.setTextColor(240, 242, 255);
      const wrapped = pdf.splitTextToSize(clean(line.slice(2)), CW);
      pdf.text(wrapped, ML, y);
      y += wrapped.length * 9 + 5;

    } else if (line.startsWith("## ")) {
      guard(12);
      // Subtle separator above section heading
      pdf.setDrawColor(55, 58, 75);
      pdf.setLineWidth(0.3);
      pdf.line(ML, y - 1, PW - MR, y - 1);
      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(14);
      pdf.setTextColor(165, 170, 255);
      const wrapped = pdf.splitTextToSize(clean(line.slice(3)), CW);
      pdf.text(wrapped, ML, y + 4);
      y += wrapped.length * 6.5 + 5;

    } else if (line.startsWith("### ")) {
      guard(8);
      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(11);
      pdf.setTextColor(200, 205, 255);
      const wrapped = pdf.splitTextToSize(clean(line.slice(4)), CW);
      pdf.text(wrapped, ML, y);
      y += wrapped.length * 5.5 + 3;

    } else if (line.startsWith("- ") || line.startsWith("* ")) {
      const body = clean(line.slice(2));
      pdf.setFont("helvetica", "normal");
      pdf.setFontSize(10);
      pdf.setTextColor(180, 185, 210);
      const wrapped = pdf.splitTextToSize(body, CW - 5);
      guard(wrapped.length * 5 + 2);
      pdf.setTextColor(99, 102, 241);
      pdf.text("•", ML, y);
      pdf.setTextColor(180, 185, 210);
      pdf.text(wrapped, ML + 5, y);
      y += wrapped.length * 5 + 2;

    } else {
      const body = clean(line);
      pdf.setFont("helvetica", "normal");
      pdf.setFontSize(10);
      pdf.setTextColor(180, 185, 210);
      const wrapped = pdf.splitTextToSize(body, CW);
      guard(wrapped.length * 5.2 + 3);
      pdf.text(wrapped, ML, y);
      y += wrapped.length * 5.2 + 3;
    }
  }

  // Sources section
  guard(16);
  y += 4;
  pdf.setDrawColor(55, 58, 75);
  pdf.setLineWidth(0.3);
  pdf.line(ML, y - 2, PW - MR, y - 2);
  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(13);
  pdf.setTextColor(165, 170, 255);
  pdf.text("Sources", ML, y + 3);
  y += 10;

  sources.forEach((s, i) => {
    guard(8);
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(9);
    // Index number
    pdf.setTextColor(120, 125, 160);
    pdf.text(`${i + 1}.`, ML, y);
    // Domain in accent colour
    pdf.setTextColor(99, 149, 237);
    pdf.text(s.domain, ML + 7, y);
    // URL in muted colour
    const urlText = pdf.splitTextToSize(s.url, CW - 30);
    pdf.setTextColor(100, 105, 140);
    pdf.text(urlText, ML + 7 + pdf.getTextWidth(s.domain) + 3, y);
    y += urlText.length * 4.5 + 2;
  });

  // Footer on every page
  const totalPages = (pdf as unknown as { internal: { getNumberOfPages: () => number } }).internal.getNumberOfPages();
  for (let p = 1; p <= totalPages; p++) {
    pdf.setPage(p);
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(8);
    pdf.setTextColor(80, 85, 110);
    pdf.text(`Page ${p} of ${totalPages}`, PW / 2, PH - 8, { align: "center" });
    pdf.text("Generated by Research Agent", ML, PH - 8);
  }

  const filename = title
    ? `${title.toLowerCase().replace(/[^a-z0-9]+/g, "-").slice(0, 60)}.pdf`
    : "research-report.pdf";

  pdf.save(filename);
}

export default function ReportView({ markdown, sources }: { markdown: string; sources: Source[] }) {
  const articleRef = useRef<HTMLElement>(null);
  const copy = () => navigator.clipboard.writeText(markdown);

  const titleLine = markdown.split("\n").find((l) => l.startsWith("# "));
  const title = titleLine ? titleLine.slice(2).trim() : "research-report";

  const handleDownload = async (btn: HTMLButtonElement) => {
    const original = btn.innerHTML;
    btn.innerHTML = "Generating…";
    btn.disabled = true;
    try {
      await downloadPDF(markdown, sources, title);
    } finally {
      btn.innerHTML = original;
      btn.disabled = false;
    }
  };

  return (
    <article ref={articleRef} className="glass mx-auto max-w-3xl p-8">
      <div className="mb-4 flex justify-end gap-2 text-sm">
        <button
          onClick={copy}
          className="rounded-lg border border-white/10 px-3 py-1 hover:bg-white/5"
        >
          Copy markdown
        </button>
        <button
          onClick={(e) => handleDownload(e.currentTarget)}
          className="rounded-lg border border-white/10 px-3 py-1 hover:bg-white/5 flex items-center gap-1.5"
        >
          <svg xmlns="http://www.w3.org/2000/svg" width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
            <path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4"/>
            <polyline points="7 10 12 15 17 10"/>
            <line x1="12" y1="15" x2="12" y2="3"/>
          </svg>
          Download PDF
        </button>
      </div>
      {markdown.split("\n").filter(Boolean).map((line, i) =>
        line.startsWith("# ") ? <h1 key={i} className="mb-4 text-3xl font-semibold">{line.slice(2)}</h1>
        : line.startsWith("## ") ? <h2 key={i} className="mb-2 mt-6 text-xl font-semibold">{line.slice(3)}</h2>
        : <p key={i} className="leading-7 text-gray-300">{withCitations(line, sources)}</p>
      )}
      <h2 className="mb-2 mt-8 text-lg font-semibold">Sources</h2>
      <ol className="list-decimal space-y-1 pl-5 text-sm text-[var(--muted)]">
        {sources.map((s, i) => (
          <li key={i}>
            <a href={s.url} className="hover:text-white" target="_blank" rel="noreferrer">
              {s.domain}
            </a>
          </li>
        ))}
      </ol>
    </article>
  );
}
